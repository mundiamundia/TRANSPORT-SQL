CREATE OR REPLACE FUNCTION fn_service_due(p_vehicle_id integer)
RETURNS boolean LANGUAGE plpgsql AS $$
DECLARE v_current integer; v_last integer;
BEGIN
 SELECT current_odometer,last_service_odometer INTO v_current,v_last FROM vehicles WHERE vehicle_id=p_vehicle_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle ID %',p_vehicle_id; END IF;
 RETURN (v_current-v_last)>=5000;
END $$;

CREATE OR REPLACE FUNCTION trg_trip_update_odometer_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_current integer;
BEGIN
 SELECT current_odometer INTO v_current FROM vehicles WHERE vehicle_id=NEW.vehicle_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle'; END IF;
 IF NEW.end_odometer<=NEW.start_odometer THEN RAISE EXCEPTION 'End odometer must exceed start odometer'; END IF;
 IF NEW.start_odometer<>v_current THEN RAISE EXCEPTION 'Trip start must equal current odometer (%)',v_current; END IF;
 UPDATE vehicles SET current_odometer=NEW.end_odometer WHERE vehicle_id=NEW.vehicle_id;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_trip_update_odometer BEFORE INSERT ON trips
FOR EACH ROW EXECUTE FUNCTION trg_trip_update_odometer_fn();

CREATE OR REPLACE PROCEDURE pr_record_trip(p_vehicle_id integer,p_trip_on date,p_start integer,p_end integer)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM vehicles WHERE vehicle_id=p_vehicle_id) THEN RAISE EXCEPTION 'Unknown vehicle'; END IF;
 IF p_trip_on IS NULL OR p_start IS NULL OR p_end IS NULL OR p_end<=p_start THEN RAISE EXCEPTION 'Invalid trip date or odometer values'; END IF;
 INSERT INTO trips(vehicle_id,trip_on,start_odometer,end_odometer)
 VALUES(p_vehicle_id,p_trip_on,p_start,p_end);
END $$;

