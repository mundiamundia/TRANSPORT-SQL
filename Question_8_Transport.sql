DROP SCHEMA IF EXISTS q8_transport CASCADE;
CREATE SCHEMA q8_transport;
SET search_path TO q8_transport,public;

CREATE TABLE vehicles(
 vehicle_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registration varchar(30) NOT NULL UNIQUE,
 current_odometer integer NOT NULL CHECK(current_odometer>=0),
 last_service_odometer integer NOT NULL CHECK(last_service_odometer>=0 AND last_service_odometer<=current_odometer)
);
CREATE TABLE trips(
 trip_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id integer NOT NULL REFERENCES vehicles(vehicle_id),
 trip_on date NOT NULL,start_odometer integer NOT NULL CHECK(start_odometer>=0),
 end_odometer integer NOT NULL CHECK(end_odometer>start_odometer)
);
CREATE TABLE service_alerts(
 vehicle_id integer PRIMARY KEY REFERENCES vehicles(vehicle_id),
 km_since_service integer NOT NULL,flagged_on date NOT NULL
);
